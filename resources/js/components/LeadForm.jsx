import { useEffect, useMemo, useRef, useState } from 'react';
import { AlertCircle, Hash, Loader2, Lock } from 'lucide-react';
import Card from './Card';
import FormInput from './FormInput';
import FormSelect from './FormSelect';
import FormTextarea from './FormTextarea';
import DatePicker from './DatePicker';
import { getJson } from '@/lib/utils';

/**
 * Shared create/edit lead form. Branch → campaign options come from props (already scoped by
 * the server); advisors and campaign statuses are loaded on demand from the lookup endpoint.
 */
export default function LeadForm({ form, branches, titles, branchLocked, canSetDate, canAssign, currentUserId, leadNumber, isPreview, abilities, currentOptions }) {
    const { data, setData, errors } = form;
    const [options, setOptions] = useState({ managers: [], lead_statuses: [], payment_statuses: [] });
    const [loadingOptions, setLoadingOptions] = useState(false);
    const [optionsError, setOptionsError] = useState(null);
    const userChangedCampaign = useRef(false);

    const can = abilities ?? { editDetails: true, changeBranch: !branchLocked, assign: canAssign, updateStatus: true, updatePaymentStatus: true };
    const branch = useMemo(() => branches.find((b) => String(b.id) === String(data.branch_id)), [branches, data.branch_id]);
    const campaigns = branch?.campaigns ?? [];

    // Load advisors + statuses whenever the branch/campaign combination changes.
    useEffect(() => {
        if (!data.branch_id || !data.campaign_id) {
            setOptions({ managers: [], lead_statuses: [], payment_statuses: [] });
            return;
        }
        let cancelled = false;
        setLoadingOptions(true);
        setOptionsError(null);
        getJson(`/lookup/branches/${data.branch_id}/campaigns/${data.campaign_id}`)
            .then((res) => {
                if (cancelled) return;
                // Keep the lead's current (possibly deactivated) values selectable on edit.
                const merge = (list, current) => (current && !list.some((i) => i.id === current.id) ? [...list, { ...current, name: `${current.name} (inactive)` }] : list);
                const next = {
                    managers: userChangedCampaign.current ? res.managers : merge(res.managers, currentOptions?.assignee),
                    lead_statuses: userChangedCampaign.current ? res.lead_statuses : merge(res.lead_statuses, currentOptions?.lead_status),
                    payment_statuses: userChangedCampaign.current ? res.payment_statuses : merge(res.payment_statuses, currentOptions?.payment_status),
                };
                setOptions(next);
                if (userChangedCampaign.current) {
                    const defLead = res.lead_statuses.find((s) => s.is_default) ?? res.lead_statuses[0];
                    const defPay = res.payment_statuses.find((s) => s.is_default) ?? res.payment_statuses[0];
                    const self = !canAssign && res.managers.find((m) => m.id === currentUserId);
                    setData((d) => ({ ...d, lead_status_id: defLead?.id ?? '', payment_status_id: defPay?.id ?? '', assigned_to: self ? self.id : '' }));
                }
            })
            .catch(() => !cancelled && setOptionsError('Could not load advisors and statuses for this campaign.'))
            .finally(() => !cancelled && setLoadingOptions(false));
        return () => {
            cancelled = true;
        };
    }, [data.branch_id, data.campaign_id]); // eslint-disable-line react-hooks/exhaustive-deps

    const onBranchChange = (value) => {
        userChangedCampaign.current = true;
        setData((d) => ({ ...d, branch_id: value, campaign_id: '', assigned_to: '', lead_status_id: '', payment_status_id: '' }));
    };
    const onCampaignChange = (value) => {
        userChangedCampaign.current = true;
        setData((d) => ({ ...d, campaign_id: value, assigned_to: '', lead_status_id: '', payment_status_id: '' }));
    };

    const dependentPlaceholder = !data.campaign_id ? 'Select a campaign first' : loadingOptions ? 'Loading…' : undefined;
    const noManagers = data.campaign_id && !loadingOptions && options.managers.length === 0;
    const toOptions = (list) => list.map((i) => ({ value: i.id, label: i.name }));

    return (
        <div className="space-y-6">
            {(errors.form || optionsError) && (
                <div className="flex items-start gap-2 rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-700">
                    <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
                    {errors.form || optionsError}
                </div>
            )}

            <Card title="Lead information" description="The lead ID is generated by the system and cannot be changed.">
                <div className="grid grid-cols-1 gap-5 sm:grid-cols-2">
                    <FormInput label="Lead ID" name="lead_number" value={leadNumber ?? ''} disabled readOnly icon={Hash} hint={isPreview ? 'Preview — the final ID is assigned when the lead is saved.' : undefined} />
                    {canSetDate && can.editDetails ? (
                        <DatePicker label="Date" name="lead_date" value={data.lead_date ?? ''} max={new Date().toISOString().slice(0, 10)} onChange={(e) => setData('lead_date', e.target.value)} error={errors.lead_date} required />
                    ) : (
                        <DatePicker label="Date" name="lead_date" value={data.lead_date ?? ''} disabled readOnly hint={isPreview ? 'Defaults to today.' : undefined} />
                    )}
                </div>
            </Card>

            <Card title="Customer details">
                <fieldset disabled={!can.editDetails} className="grid grid-cols-1 gap-5 sm:grid-cols-6">
                    <FormSelect label="Title" name="title" className="sm:col-span-1" value={data.title ?? ''} onChange={(e) => setData('title', e.target.value)} options={titles.map((t) => ({ value: t, label: `${t}.` }))} placeholder="—" error={errors.title} />
                    <FormInput label="First name" name="first_name" className="sm:col-span-2" value={data.first_name} onChange={(e) => setData('first_name', e.target.value)} error={errors.first_name} required autoComplete="off" />
                    <FormInput label="Last name" name="last_name" className="sm:col-span-3" value={data.last_name ?? ''} onChange={(e) => setData('last_name', e.target.value)} error={errors.last_name} autoComplete="off" />
                    <FormInput label="Mobile number" name="mobile" type="tel" className="sm:col-span-3" value={data.mobile} onChange={(e) => setData('mobile', e.target.value)} error={errors.mobile} required placeholder="07700 900123" />
                    <FormInput label="Email" name="email" type="email" className="sm:col-span-3" value={data.email ?? ''} onChange={(e) => setData('email', e.target.value)} error={errors.email} placeholder="name@example.com" />
                    <FormInput label="House number" name="house_number" className="sm:col-span-3" value={data.house_number ?? ''} onChange={(e) => setData('house_number', e.target.value)} error={errors.house_number} />
                    <FormInput label="Post code" name="post_code" className="sm:col-span-3" value={data.post_code ?? ''} onChange={(e) => setData('post_code', e.target.value.toUpperCase())} error={errors.post_code} />
                </fieldset>
            </Card>

            <Card title="Assignment" description="Advisors are limited to active managers of the selected branch and campaign.">
                <div className="grid grid-cols-1 gap-5 sm:grid-cols-3">
                    {branchLocked || !can.changeBranch ? (
                        <FormInput label="Branch" name="branch_display" value={branch?.name ?? ''} disabled readOnly icon={Lock} error={errors.branch_id} />
                    ) : (
                        <FormSelect label="Branch" name="branch_id" value={data.branch_id ?? ''} onChange={(e) => onBranchChange(e.target.value)} options={toOptions(branches)} placeholder="Select branch" error={errors.branch_id} required />
                    )}
                    <FormSelect
                        label="Campaign"
                        name="campaign_id"
                        value={data.campaign_id ?? ''}
                        onChange={(e) => onCampaignChange(e.target.value)}
                        options={toOptions(campaigns)}
                        placeholder={!data.branch_id ? 'Select a branch first' : campaigns.length ? 'Select campaign' : 'No campaigns available'}
                        disabled={!data.branch_id || !can.editDetails}
                        error={errors.campaign_id}
                        required
                    />
                    <div>
                        <FormSelect
                            label="Campaign manager / Advisor"
                            name="assigned_to"
                            value={data.assigned_to ?? ''}
                            onChange={(e) => setData('assigned_to', e.target.value)}
                            options={toOptions(options.managers)}
                            placeholder={dependentPlaceholder ?? (noManagers ? 'No eligible advisors' : 'Unassigned')}
                            disabled={!data.campaign_id || loadingOptions || !can.assign}
                            error={errors.assigned_to}
                        />
                        {noManagers && !errors.assigned_to && <p className="mt-1.5 text-xs text-amber-600">No active managers are assigned to this campaign in this branch.</p>}
                    </div>
                </div>
            </Card>

            <Card title="Status" actions={loadingOptions && <Loader2 className="h-4 w-4 animate-spin text-primary-500" />}>
                <div className="grid grid-cols-1 gap-5 sm:grid-cols-3">
                    <FormSelect label="Lead status" name="lead_status_id" value={data.lead_status_id ?? ''} onChange={(e) => setData('lead_status_id', e.target.value)} options={toOptions(options.lead_statuses)} placeholder={dependentPlaceholder ?? 'Campaign default'} disabled={!data.campaign_id || loadingOptions || !can.updateStatus} error={errors.lead_status_id} />
                    <FormSelect label="Payment status" name="payment_status_id" value={data.payment_status_id ?? ''} onChange={(e) => setData('payment_status_id', e.target.value)} options={toOptions(options.payment_statuses)} placeholder={dependentPlaceholder ?? 'Campaign default'} disabled={!data.campaign_id || loadingOptions || !can.updatePaymentStatus} error={errors.payment_status_id} />
                    <DatePicker label="Follow-up date" name="follow_up_date" value={data.follow_up_date ?? ''} onChange={(e) => setData('follow_up_date', e.target.value)} disabled={!can.updateStatus} error={errors.follow_up_date} />
                </div>
            </Card>

            <Card title="Notes">
                <FormTextarea name="notes" value={data.notes ?? ''} onChange={(e) => setData('notes', e.target.value)} rows={5} placeholder="Background, requirements, call outcomes…" disabled={!can.editDetails} error={errors.notes} hint="For a dated record of updates, add notes from the lead's detail page." />
            </Card>
        </div>
    );
}
